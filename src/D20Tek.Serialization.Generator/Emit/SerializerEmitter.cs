namespace D20Tek.Serialization.Generation;

/// <summary>
/// Emits the C# source for a generated <c>IGeneratedSerializer&lt;T&gt;</c> implementation for a
/// single <see cref="SerializableTypeModel"/>.
/// </summary>
internal static class SerializerEmitter
{
    public const string GeneratedNamespace = "D20Tek.Serialization.Generated";

    public static string Emit(SerializableTypeModel model)
    {
        var writer = new SourceWriter();
        var readReturnType = model.IsValueType ? model.FullyQualifiedName : model.FullyQualifiedName + "?";

        EmitHeader(writer);
        writer.Line($"namespace {GeneratedNamespace}");
        writer.OpenBrace();

        writer.Line("/// <summary>");
        writer.Line($"/// Generated serializer for <see cref=\"{model.FullyQualifiedName}\"/>.");
        writer.Line("/// </summary>");
        writer.Line(
            $"internal sealed class {model.SerializerTypeName} : " +
            $"global::D20Tek.Serialization.Generation.IGeneratedSerializer<{model.FullyQualifiedName}>");
        writer.OpenBrace();

        WriteMemberEmitter.EmitWrite(writer, model);
        writer.Line();
        ReadMemberEmitter.EmitRead(writer, model, readReturnType);

        writer.CloseBrace();
        writer.CloseBrace();

        return writer.ToString();
    }

    private static void EmitHeader(SourceWriter writer)
    {
        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line();
    }
}
